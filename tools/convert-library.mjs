// Converts the legacy nakal.data.js library into clean JSON (for development)
// and a SQL seed (for the Supabase library tables).
// Usage: node tools/convert-library.mjs <path-to-nakal.data.js>
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import vm from 'node:vm';

const [src, jsonDir = 'data/library', sqlDir = 'supabase'] = process.argv.slice(2);
if (!src) { console.error('usage: convert-library.mjs <nakal.data.js> [jsonDir] [sqlDir]'); process.exit(1); }

const ctx = { nakal: {}, console };
vm.createContext(ctx);
vm.runInContext(readFileSync(src, 'utf8'), ctx);
const data = ctx.nakal.data;

const step = (s) => ({ index: s.Index, diameter: s.Diameter, depth: s.Depth, angle: s.Angle });
const port = (p) => ({ diameter: p.Diameter, depth: p.Depth, connectingCavity: p.ConnectingCavity });
const oring = (o) => ({ diameter: o.Diameter, depth: o.Depth, width: o.Width });
const thread = (t) => ({ size: t.Size, step: t.Cricle, cls: t.Class, pitch: t.Pitch });
const machine = (m) => ({ diameter: m.Diameter, depth: m.Depth, operation: m.Operation, tool: m.Tool });

const cavities = data.cavities.map((c) => ({
  id: c.CavityIndex,
  name: c.CavityName,
  type: c.CavityType,
  library: c.LibraryName,
  steps: c.Cricles.map(step),
  ports: c.Ports.map(port),
  numberOfPorts: c.NumberofPorts,
  orings: c.ORings.map(oring),
  threads: c.Threads.map(thread),
  machines: c.Machines.map(machine),
  isFootprint: !!c.IsFootPrint,
  // Per-library footprint counter; children match on (library, this index).
  footprintIndex: c.CavityFootPrintIndex ?? null,
  insertionDepth: c.InsertionDepth,
  plugHeadHeight: c.PlugHeadHeight,
  maxPressure: c.MaxPressure,
  portApplicationName: c.PortApplicationName ?? null,
  comments: c.Comments ?? null,
}));

const footprints = data.footprints.map((f) => ({
  footprintIndex: f.FootprintIndex,
  parentCavityId: f.CavityIndex,
  type: f.CavityType,
  library: f.LibraryName,
  portApplicationName: f.PortApplicationName ?? null,
  x: f.CavityXDim,
  y: f.CavityYDim,
  steps: f.Cricles.map((s, i) => ({ ...step(s), index: s.Index ?? i })),
  ports: f.Ports.map(port),
  threads: f.Threads.map(thread),
  machines: f.Machines.map(machine),
}));

mkdirSync(jsonDir, { recursive: true });
writeFileSync(join(jsonDir, 'cavities.json'), JSON.stringify(cavities));
writeFileSync(join(jsonDir, 'footprints.json'), JSON.stringify(footprints));

// SQL seed, in batches so the Supabase SQL editor handles it comfortably.
const q = (obj) => `'${JSON.stringify(obj).replace(/'/g, "''")}'::jsonb`;
const batches = (rows, size) => Array.from({ length: Math.ceil(rows.length / size) }, (_, i) => rows.slice(i * size, (i + 1) * size));
let sql = '-- Generated by tools/convert-library.mjs. Run after schema.sql.\n';
sql += 'delete from public.library_footprints;\n';
for (const b of batches(cavities, 50)) {
  sql += 'insert into public.library_cavities (id, data) values\n' +
    b.map((c) => `  (${c.id}, ${q(c)})`).join(',\n') +
    '\non conflict (id) do update set data = excluded.data;\n';
}
for (const b of batches(footprints, 50)) {
  sql += 'insert into public.library_footprints (data) values\n' + b.map((f) => `  (${q(f)})`).join(',\n') + ';\n';
}
mkdirSync(sqlDir, { recursive: true });
writeFileSync(join(sqlDir, 'seed_library.sql'), sql);
console.log(`cavities ${cavities.length}, footprints ${footprints.length} -> ${jsonDir}, ${sqlDir}/seed_library.sql (${(sql.length / 1024).toFixed(0)} KB)`);
